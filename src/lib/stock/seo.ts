import type { Metadata } from "next";
import { DEALER_ADDRESS, DEALER_LOCATION, DEALER_TEL, SITE_NAME, SITE_URL } from "@/lib/site";
import { carName, carTitle, formatKm, fmtEur, carHref } from "./format";
import { FUEL_LABELS, GEARBOX_LABELS, isSold, onRequest } from "./types";
import { PRICING } from "./pricing.config";
import { knownKm } from "./markers";
import type { Car } from "./types";

// The sale date never enters metadata or JSON-LD (owner instruction, 2026-11-06).
export function carDescription(car: Car): string {
  const km = knownKm(car);
  const specs = [km !== undefined && formatKm(km), car.fuel && FUEL_LABELS[car.fuel], car.gearbox && GEARBOX_LABELS[car.gearbox]].filter(Boolean).join(", ");
  return [`${car.year} ${carTitle(car)}.`, specs && `${specs}.`, isSold(car) ? "Sold." : onRequest(car) ? `${PRICING.labels.onRequest}.` : `${fmtEur(car.priceEur)}.`, `${SITE_NAME}, ${DEALER_LOCATION}.`].filter(Boolean).join(" ");
}

// No site suffix in the title: the root layout's template adds it. Image and url resolve to absolute against metadataBase.
// The images of the stock that ships with the site are pre-generated by `npm run stock:og` (photos under /stock/). A car added in the
// dashboard has none, so it shares its first photo, or no image when that photo is inline.
export function carMetadata(car: Car): Metadata {
  const title = `${car.year} ${carTitle(car)}${isSold(car) ? "" : " for sale"}`;
  const description = carDescription(car);
  const path = carHref(car.slug);
  const first = car.photos[0];
  const shipped = !first || first.src.startsWith("/stock/");
  const images = shipped ? [{ url: `/og/${car.id}.jpg`, width: 1200, height: 630, alt: carName(car) }] : first.src.startsWith("data:") ? [] : [{ url: first.src, width: first.width, height: first.height, alt: carName(car) }];
  return { title, description, alternates: { canonical: path }, openGraph: { type: "website", url: path, title, description, images }, twitter: { card: "summary_large_image" } };
}

// Google does not treat Car as a Product subtype, so both types. A sold car keeps a price-less SoldOut offer; a reserved one is OutOfStock (schema.org has no reserved value). Undefined values vanish in JSON.stringify.
export function carJsonLd(car: Car): Record<string, unknown> {
  const url = `${SITE_URL}${carHref(car.slug)}`;
  const sold = isSold(car);
  const km = knownKm(car);
  return {
    "@context": "https://schema.org",
    "@type": ["Product", "Car"],
    name: `${car.year} ${carTitle(car)}`,
    description: carDescription(car),
    url,
    image: car.photos.length ? car.photos.map((p) => `${SITE_URL}${p.src}`) : undefined,
    brand: { "@type": "Brand", name: car.make },
    model: car.model,
    vehicleModelDate: String(car.year),
    itemCondition: "https://schema.org/UsedCondition",
    mileageFromOdometer: km === undefined ? undefined : { "@type": "QuantitativeValue", value: km, unitCode: "KMT" },
    fuelType: car.fuel && FUEL_LABELS[car.fuel],
    vehicleTransmission: car.gearbox && GEARBOX_LABELS[car.gearbox],
    bodyType: car.bodyType,
    numberOfDoors: car.doors,
    vehicleSeatingCapacity: car.seats,
    numberOfPreviousOwners: car.owners,
    color: car.colour,
    vehicleEngine: car.engineLitres === undefined ? undefined : { "@type": "EngineSpecification", engineDisplacement: { "@type": "QuantitativeValue", value: car.engineLitres, unitCode: "LTR" } },
    offers: onRequest(car) ? undefined : { // no price, no offer Google can read
      "@type": "Offer",
      url,
      itemCondition: "https://schema.org/UsedCondition",
      availability: sold ? "https://schema.org/SoldOut" : car.reserved ? "https://schema.org/OutOfStock" : "https://schema.org/InStock",
      price: sold ? undefined : car.priceEur,
      priceCurrency: sold ? undefined : "EUR",
      seller: {
        "@type": "AutoDealer",
        name: SITE_NAME,
        telephone: DEALER_TEL,
        address: { "@type": "PostalAddress", addressLocality: DEALER_ADDRESS.town, addressRegion: DEALER_ADDRESS.county.replace(/^Co. /, ""), addressCountry: "IE" },
      },
    },
  };
}
